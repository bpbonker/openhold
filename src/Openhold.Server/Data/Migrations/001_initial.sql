-- Openhold initial schema. Runs on the authority (primary); site replicas receive it via streaming replication.

CREATE TABLE sites (
    id           text PRIMARY KEY,           -- short code used in numbering, e.g. 'AU', 'IN'
    name         text NOT NULL,
    base_url     text,
    is_authority boolean NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX sites_single_authority ON sites (is_authority) WHERE is_authority;

CREATE TABLE users (
    id           uuid PRIMARY KEY,
    username     text NOT NULL,
    display_name text NOT NULL,
    email        text,
    home_site    text REFERENCES sites (id),
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_username_ci ON users (lower(username));

CREATE TABLE folders (
    id         uuid PRIMARY KEY,
    parent_id  uuid REFERENCES folders (id),
    name       text NOT NULL,
    path       text NOT NULL,                -- '$', '$/Electrical', '$/Electrical/Project A'
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((parent_id IS NULL) = (path = '$'))
);

CREATE UNIQUE INDEX folders_path_ci ON folders (lower(path));
CREATE INDEX folders_parent ON folders (parent_id);

INSERT INTO folders (id, parent_id, name, path) VALUES ('00000000-0000-0000-0000-000000000001', NULL, '$', '$');

CREATE TABLE files (
    id                  uuid PRIMARY KEY,
    folder_id           uuid NOT NULL REFERENCES folders (id),
    name                text NOT NULL,
    requires_unique_name boolean NOT NULL,   -- CAD files resolved by name must be unique vault-wide
    latest_version      int NOT NULL DEFAULT 0,
    created_by          uuid NOT NULL REFERENCES users (id),
    created_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz
);

CREATE UNIQUE INDEX files_folder_name_ci ON files (folder_id, lower(name)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX files_unique_cad_name_ci ON files (lower(name)) WHERE requires_unique_name AND deleted_at IS NULL;

-- A changeset is one atomic check-in. Its id is generated by the client so retries
-- (e.g. a site outbox draining after a WAN outage) are idempotent.
CREATE TABLE changesets (
    id           uuid PRIMARY KEY,
    user_id      uuid NOT NULL REFERENCES users (id),
    site_id      text NOT NULL REFERENCES sites (id),
    machine      text NOT NULL,
    comment      text NOT NULL DEFAULT '',
    committed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE file_versions (
    file_id      uuid NOT NULL REFERENCES files (id),
    version      int NOT NULL CHECK (version > 0),
    changeset_id uuid NOT NULL REFERENCES changesets (id),
    length       bigint NOT NULL,
    content_hash bytea NOT NULL,
    manifest     bytea NOT NULL,             -- ManifestCodec encoding of the chunk list
    origin_site  text NOT NULL REFERENCES sites (id),
    properties   jsonb NOT NULL DEFAULT '{}',
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (file_id, version)
);

CREATE INDEX file_versions_changeset ON file_versions (changeset_id);

CREATE TABLE file_references (
    parent_file_id uuid NOT NULL,
    parent_version int NOT NULL,
    child_file_id  uuid NOT NULL REFERENCES files (id),
    child_version  int NOT NULL,
    ref_path       text,                     -- path as stored in the parent, for diagnostics and repair
    PRIMARY KEY (parent_file_id, parent_version, child_file_id),
    FOREIGN KEY (parent_file_id, parent_version) REFERENCES file_versions (file_id, version)
);

CREATE INDEX file_references_child ON file_references (child_file_id);

-- One row per checked-out file; the primary key is what makes double checkout impossible.
CREATE TABLE locks (
    file_id      uuid PRIMARY KEY REFERENCES files (id),
    user_id      uuid NOT NULL REFERENCES users (id),
    site_id      text NOT NULL REFERENCES sites (id),
    machine      text NOT NULL,
    state        text NOT NULL DEFAULT 'held' CHECK (state IN ('held', 'committing')),
    base_version int NOT NULL,
    acquired_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX locks_user ON locks (user_id);

CREATE FUNCTION notify_lock_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_notify('openhold_locks', COALESCE(NEW.file_id, OLD.file_id)::text);
    RETURN NULL;
END $$;

CREATE TRIGGER locks_notify AFTER INSERT OR UPDATE OR DELETE ON locks
    FOR EACH ROW EXECUTE FUNCTION notify_lock_change();

CREATE TABLE numbering_schemes (
    id              text PRIMARY KEY,
    name            text NOT NULL,
    template        text NOT NULL,           -- NumberTemplate syntax, e.g. 'EL-{seq:000000}'
    next_value      bigint NOT NULL DEFAULT 1,
    allow_reuse     boolean NOT NULL DEFAULT false,
    reservation_ttl interval NOT NULL DEFAULT '24 hours',
    enabled         boolean NOT NULL DEFAULT true
);

CREATE TABLE number_reservations (
    scheme_id   text NOT NULL REFERENCES numbering_schemes (id),
    value       bigint NOT NULL,
    formatted   text NOT NULL,
    state       text NOT NULL CHECK (state IN ('reserved', 'committed', 'released', 'expired')),
    reserved_by uuid NOT NULL REFERENCES users (id),
    site_id     text NOT NULL REFERENCES sites (id),
    reserved_at timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL,
    file_id     uuid REFERENCES files (id),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (scheme_id, value)
);

CREATE UNIQUE INDEX number_reservations_formatted_ci ON number_reservations (lower(formatted));
CREATE INDEX number_reservations_expiry ON number_reservations (expires_at) WHERE state = 'reserved';

CREATE TABLE audit_events (
    id           bigserial PRIMARY KEY,
    at           timestamptz NOT NULL DEFAULT now(),
    user_id      uuid,
    site_id      text,
    action       text NOT NULL,
    file_id      uuid,
    changeset_id uuid,
    data         jsonb NOT NULL DEFAULT '{}'
);

CREATE INDEX audit_events_file ON audit_events (file_id, at);
